import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import type { Plugin } from "vite";
import { SECURITY_HEADERS } from "../worker/security-headers";

/**
 * Writes the security headers into `dist/client/_headers`, for the responses the
 * Worker never sees.
 *
 * `worker/index.ts` wraps everything it answers, and for a while that looked like
 * the whole job. It is not: Cloudflare's static asset handler runs *before* the
 * Worker and answers anything it has a file for, so `/assets/*`, `/demos/*`,
 * `/fun/*` and `/derived/*` never reach that wrapper. Measured on a real preview,
 * the documents carried all six headers and the stylesheet, the client bundle, the
 * vendored choir app and every clip in the gallery carried none — which is the wrong
 * way round for `nosniff`, and leaves the framed application governed by no policy at
 * all.
 *
 * `_headers` is how the asset handler is told, and it costs no Worker invocation.
 * The alternative is `run_worker_first: true`, which bills one for every image.
 *
 * Generated rather than checked in, because a second copy of a policy is a second
 * policy: the values come from the same module the Worker imports, so the two cannot
 * drift. vinext writes this file itself when it is absent, to make hashed assets
 * immutable, and its rule is reproduced below — this plugin runs after it and would
 * otherwise silently drop a year of caching.
 */
export function securityHeadersFile(): Plugin {
  let root = process.cwd();

  return {
    name: "security-headers-file",
    apply: "build",
    configResolved(config) {
      root = config.root;
    },
    async closeBundle() {
      const target = resolve(root, "dist", "client", "_headers");

      const lines = [
        "# Generated by build/security-headers-vite-plugin.ts. Do not edit.",
        "#",
        "# The Worker sets these on everything it answers; this is the same set for the",
        "# static assets Cloudflare serves without invoking it. Source of truth for both:",
        "# worker/security-headers.ts.",
        "/*",
        ...Object.entries(SECURITY_HEADERS).map(([name, value]) => `  ${name}: ${value}`),
        "",
        "# vinext's own rule, kept because this file replaces the one it writes.",
        "/assets/*",
        "  Cache-Control: public, max-age=31536000, immutable",
        "",
      ];

      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, lines.join("\n"), "utf8");
    },
  };
}
